def primary_language(value: str | None) -> str | None:
    """`zh-CN` -> `zh`, `en_US` -> `en`; None for an empty value."""
    if not value:
        return None
    primary = value.strip().replace("_", "-").split("-", 1)[0].lower()
    return primary or None


def whisper_language(value: str | None) -> str | None:
    """The normalised code if Whisper knows it, otherwise None."""
    code = primary_language(value)
    return code if code in WHISPER_LANGUAGES else None
