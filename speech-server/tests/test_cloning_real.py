def _make_voice(engines, store, text, kokoro_voice, language, name):
    tts = engines.tts
    audio = np.concatenate(list(tts.synthesize(text, kokoro_voice)))
    wav = wav_bytes(float_to_pcm16(audio), tts.sample_rate)
    return store.create(
        audio=wav, name=name, transcript=text, languages=language, gender="neutral", **CONSENT
    ).id


@pytest.fixture(scope="module")
def voices(stack):
    engines, store, _ = stack
    zh_voice = engines.tts.default_voice("female", "zh")
    return {
        "en": _make_voice(engines, store, REF_EN, "af_heart", "en", "heart"),
        "male": _make_voice(engines, store, REF_EN, "am_michael", "en", "michael"),
        "zh": _make_voice(engines, store, REF_ZH, zh_voice, "zh", "zh"),
    }


def _speak(router, text, voice):
    audio = np.concatenate(list(router.synthesize(text, voice)))
    return resample(audio, router.sample_rate, INPUT_RATE)


def test_cloned_english_is_intelligible(stack, voices):
    from bench.latency import wer

    engines, _, router = stack
    scores = []
    for text in EN:
        heard = engines.stt.transcribe(_speak(router, text, voices["en"]), INPUT_RATE, language="en").text
        scores.append(wer(text, heard))
    assert sum(scores) / len(scores) <= 0.1, scores


