def _speak(router, voice):
    audio = np.concatenate(list(router.synthesize(SAY, voice)))
    return resample(audio, router.sample_rate, INPUT_RATE)


def test_transcription_and_synthesis_at_once_stay_correct_and_never_overlap(stack, capsys, request):
    from bench.latency import wer

    engines, router, voice = stack
    stt = engines.stt
    clip = _speak(router, voice)  # what the transcription thread will keep hearing
    probe = Overlap()
    spying = spy_whisper(stt, probe)
    spying.__enter__()
    request.addfinalizer(lambda: spying.__exit__(None, None, None))
    engines.cloning._model = SpyModel(engines.cloning._model, probe)

    def timed(fn):
        start = time.perf_counter()
        for _ in range(ROUNDS):
            fn()
        return (time.perf_counter() - start) / ROUNDS

    listen = lambda: stt.transcribe(clip, INPUT_RATE, language="en").text
    speak = lambda: _speak(router, voice)
    alone_stt, alone_tts = timed(listen), timed(speak)
    assert probe.peak == 1

    heard, spoken, errors = [], [], []

    def run(fn, out):
        try:
            for _ in range(ROUNDS):
                out.append(fn())
        except Exception as exc:  # noqa: BLE001
            errors.append(exc)

    threads = [
        threading.Thread(target=run, args=(listen, heard)),
        threading.Thread(target=run, args=(speak, spoken)),
    ]
    start = time.perf_counter()
    for t in threads:
        t.start()
    for t in threads:
        t.join(300)
    together = (time.perf_counter() - start) / ROUNDS

    assert not errors, errors
    assert probe.peak == 1, "two MLX evaluations ran at the same time"
    assert len(heard) == len(spoken) == ROUNDS
    scores = [wer(SAY, h) for h in heard]
    assert max(scores) <= 0.1, (scores, heard)
    for clip_out in spoken:  # what was synthesized while transcribing is itself intelligible
        assert wer(SAY, stt.transcribe(clip_out, INPUT_RATE, language="en").text) <= 0.1
    with capsys.disabled():
        print(
            f"\nMLX gate, per round: transcribe alone {alone_stt:.2f}s, synthesize alone {alone_tts:.2f}s, "
            f"both at once {together:.2f}s (sum {alone_stt + alone_tts:.2f}s)"
        )


LONG = [
    "The road along the coast was quiet this morning, and the fog lifted slowly over the water.",
    "We stopped at a small cafe near the harbour to check the weather and refill the tank.",
    "The next fuel station is about forty kilometres ahead, after the long bridge.",
    "Traffic in the city centre is heavy, so the navigation suggests a route through the hills.",
    "There is a speed camera in two hundred metres; the limit here is sixty.",
    "My battery is at thirty percent, so remind me to charge the phone when we stop.",
]


def test_a_long_transcription_gives_live_speech_the_gpu_between_windows_and_keeps_its_text(stack, capsys):
    """A batch transcription of several 30 s windows, with live cloned sentences asking for the GPU all along: each
    sentence waits for one window at most, and the transcript is exactly the one made with nothing else running."""
    from max_speech.engines.mlx_gate import Ticket, working_for

    engines, router, voice = stack
    stt = engines.stt
    pieces, n = [], 0
    while sum(len(p) for p in pieces) < 150 * engines.tts.sample_rate:
        pieces.append(np.concatenate(list(engines.tts.synthesize(LONG[n % len(LONG)], "am_michael"))))
        pieces.append(np.zeros(engines.tts.sample_rate // 2, dtype=np.float32))
        n += 1
    long_clip = resample(np.concatenate(pieces), engines.tts.sample_rate, INPUT_RATE)

    def transcribe():
        # A window whose greedy text looks repetitive is decoded again with sampling (temperature fallback), which
        # differs from run to run. Seeding mlx's generator (kept per thread) makes the two runs comparable.
        import mlx.core as mx

        mx.random.seed(1234)
        return stt.transcribe(long_clip, INPUT_RATE, language="en")

    alone = transcribe()

    result, waits = {}, []
    batch = threading.Thread(target=lambda: result.setdefault("t", transcribe()))
    batch.start()
    time.sleep(0.3)
    while batch.is_alive():
        start = time.perf_counter()
        with working_for(Ticket(realtime=True)):
            stream = router.synthesize("Turn left at the next junction.", voice)
            next(stream)
            waits.append(time.perf_counter() - start)
            for _ in stream:
                pass
        time.sleep(
            0.3
        )  # a rider's sentences come with pauses (back-to-back ones are bounded by BATCH_PATIENCE_S)
    batch.join()
    assert result["t"].text == alone.text and result["t"].segments == alone.segments
    assert waits and max(waits) < 1.5, (
        waits
    )  # one window (0.65 s at most measured) plus the first chunk itself
    with capsys.disabled():
        print(
            f"\nwindowed transcription of {len(long_clip) / INPUT_RATE:.0f}s with {len(waits)} live sentences between "
            f"its windows: identical text; first audio waited {min(waits):.2f}-{max(waits):.2f}s"
        )
