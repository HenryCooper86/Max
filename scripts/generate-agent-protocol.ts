import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

type EventSchema = {
  title: string;
  properties: { type: { const: string } };
  required?: string[];
};

type ProtocolSchema = {
  $defs: {
    ClientEvent: { oneOf: EventSchema[] };
    AgentEvent: { oneOf: EventSchema[] };
  };
};

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = path.join(root, "protocol/agent-events.schema.json");
const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8")) as ProtocolSchema;
const client = schema.$defs.ClientEvent.oneOf;
const server = schema.$defs.AgentEvent.oneOf;
const generatedNotice =
  "Generated by scripts/generate-agent-protocol.ts from protocol/agent-events.schema.json. Do not edit.";

function camel(value: string) {
  return value.replace(/[^a-zA-Z0-9]+(.)/g, (_, next: string) => next.toUpperCase());
}

function screaming(value: string) {
  return value.replace(/[^a-zA-Z0-9]+/g, "_").toUpperCase();
}

function requiredMap(events: EventSchema[]) {
  return Object.fromEntries(events.map((event) => [event.properties.type.const, event.required ?? ["type"]]));
}

function tsOutput() {
  const renderList = (events: EventSchema[]) =>
    events.map((event) => `  ${JSON.stringify(event.properties.type.const)}`).join(",\n");
  return `// ${generatedNotice}\n\nexport const CLIENT_EVENT_TYPES = [\n${renderList(client)}\n] as const;\n\nexport const SERVER_EVENT_TYPES = [\n${renderList(server)}\n] as const;\n\nexport const SERVER_EVENT_REQUIRED_FIELDS = ${JSON.stringify(requiredMap(server), null, 2)} as const;\n`;
}

function kotlinOutput() {
  const constants = (events: EventSchema[]) =>
    events
      .map(
        (event) =>
          `    const val ${screaming(event.properties.type.const)} = ${JSON.stringify(event.properties.type.const)}`
      )
      .join("\n");
  const fields = (events: EventSchema[]) =>
    events
      .map(
        (event) =>
          `        ${JSON.stringify(event.properties.type.const)} to setOf(${(event.required ?? ["type"])
            .map((field) => JSON.stringify(field))
            .join(", ")})`
      )
      .join(",\n");
  return `// ${generatedNotice}\npackage io.github.henrycooper86.max.agent\n\nobject ClientEventTypes {\n${constants(client)}\n    val all: Set<String> = setOf(${client.map((event) => screaming(event.properties.type.const)).join(", ")})\n}\n\nobject ServerEventTypes {\n${constants(server)}\n    val all: Set<String> = setOf(${server.map((event) => screaming(event.properties.type.const)).join(", ")})\n}\n\nval SERVER_EVENT_REQUIRED_FIELDS: Map<String, Set<String>> = mapOf(\n${fields(server)}\n)\n`;
}

function swiftOutput() {
  const constants = (events: EventSchema[]) =>
    events
      .map(
        (event) =>
          `    static let ${camel(event.properties.type.const)} = ${JSON.stringify(event.properties.type.const)}`
      )
      .join("\n");
  const all = (events: EventSchema[]) => events.map((event) => camel(event.properties.type.const)).join(", ");
  const fields = (events: EventSchema[]) =>
    events
      .map(
        (event) =>
          `    ${JSON.stringify(event.properties.type.const)}: [${(event.required ?? ["type"])
            .map((field) => JSON.stringify(field))
            .join(", ")}]`
      )
      .join(",\n");
  return `// ${generatedNotice}\nimport Foundation\n\nenum ClientEventTypes {\n${constants(client)}\n    static let all: Set<String> = [${all(client)}]\n}\n\nenum ServerEventTypes {\n${constants(server)}\n    static let all: Set<String> = [${all(server)}]\n}\n\nlet serverEventRequiredFields: [String: Set<String>] = [\n${fields(server)}\n]\n`;
}

const outputs = new Map<string, string>([
  ["shared/generated/agent-protocol.ts", tsOutput()],
  ["android/app/src/main/java/io/github/henrycooper86/max/agent/GeneratedAgentProtocol.kt", kotlinOutput()],
  ["ios/MaxHelmet/Agent/GeneratedAgentProtocol.swift", swiftOutput()]
]);

const check = process.argv.includes("--check");
let stale = false;
for (const [relativePath, content] of outputs) {
  const outputPath = path.join(root, relativePath);
  if (check) {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== content) {
      console.error(`Generated protocol file is stale: ${relativePath}`);
      stale = true;
    }
    continue;
  }
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, content);
  console.log(`Generated ${relativePath}`);
}

if (stale) process.exitCode = 1;
