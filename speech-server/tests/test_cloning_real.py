def _median_f0(x: np.ndarray, rate: int) -> float:
    """Median fundamental frequency over voiced 40 ms frames, by autocorrelation (70-400 Hz)."""
    frame, hop = int(0.04 * rate), int(0.02 * rate)
    lo, hi = int(rate / 400), int(rate / 70)
    gate = 0.3 * np.sqrt(np.mean(x**2))
    out = []
    for i in range(0, len(x) - frame, hop):
        f = x[i : i + frame] - np.mean(x[i : i + frame])
        if np.sqrt(np.mean(f**2)) < gate:
            continue
        ac = np.correlate(f, f, "full")[frame - 1 :]
        if ac[0] <= 0:
            continue
        lag = lo + int(np.argmax(ac[lo:hi]))
        if ac[lag] / ac[0] > 0.5:  # clearly periodic
            out.append(rate / lag)
    assert len(out) > 20, "too few voiced frames"
    return float(np.median(out))


def test_cloned_voices_follow_their_reference(stack, voices):
    _, _, router = stack
    text = EN[0]
    female = _median_f0(_speak(router, text, voices["en"]), INPUT_RATE)
    male = _median_f0(_speak(router, text, voices["male"]), INPUT_RATE)
    # af_heart sits near 200 Hz and am_michael near 120 Hz; demand a clear gap, not exact values.
    assert female > male * 1.2, (female, male)
